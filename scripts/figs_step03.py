"""Section 3 numbers: the splits, their class balance, and what a curve-level split would leak.

    python scripts/figs_step03.py

Reads data/curves.parquet and data/features.parquet; writes notes/figures/step03_*.
"""

from pathlib import Path

import numpy as np
import pandas as pd

from eclab.data.ecdata import load_curves
from eclab.features import AP_COLUMNS, load_features
from eclab.splits import SPLITS, split
from eclab.tasks import task2_label, task2_mask

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "notes" / "figures"
SEED = 0


def lookup_attack(keys: np.ndarray, y: np.ndarray, train: np.ndarray, test: np.ndarray):
    """'Model' that predicts a test curve's label by finding a training curve with the same a_p vector.

    Returns (share of test curves with a match, accuracy on those matched).
    """
    table = pd.DataFrame({"key": keys[train], "y": y[train]}).groupby("key").y.mean()
    hit = pd.Series(keys[test]).map(table)
    matched = hit.notna().to_numpy()
    acc = ((hit[matched].to_numpy() >= 0.5) == y[test][matched]).mean() if matched.any() else float("nan")
    return matched.mean(), acc


def main():
    curves = load_curves()
    feats = load_features()
    df = curves[["iso_class", "conductor", "rank"]].assign(conductor_is_prime=feats.conductor_is_prime)
    t2 = task2_mask(df["rank"].to_numpy())

    rows = []
    for name in SPLITS:
        train, test = split(df, name)
        pi = lambda m: (df["rank"][m & t2] == 2).mean()
        rows.append((name, (train & t2).sum(), (test & t2).sum(), pi(train), pi(test)))
    table = pd.DataFrame(rows, columns=["split", "n_train", "n_test", "pi_train", "pi_test"])

    # memorization: Task 2 curves in the complete range, a_p for p < 100 as an exact key
    sub = (df.conductor.to_numpy() <= 500_000) & t2
    ap = np.ascontiguousarray(feats.loc[sub, AP_COLUMNS].to_numpy())
    keys = np.array([r.tobytes() for r in ap], dtype=object)
    y = task2_label(df["rank"].to_numpy()[sub]).astype(bool)
    cls = df.iso_class.to_numpy()[sub]

    rng = np.random.default_rng(SEED)
    curve_test = rng.random(sub.sum()) < 0.2
    class_train, class_test = split(df[sub].reset_index(drop=True), "random")
    curve_match, curve_acc = lookup_attack(keys, y, ~curve_test, curve_test)
    class_match, class_acc = lookup_attack(keys, y, class_train, class_test)

    # distinct classes that share the whole a_p vector for p < 100
    per_key = pd.DataFrame({"key": keys, "cls": cls}).drop_duplicates().groupby("key").cls.size()
    shared_keys = int((per_key > 1).sum())

    lines = ["% generated by scripts/figs_step03.py; do not edit"]
    names = {"random": "Random", "conductor": "Conductor", "prime": "Prime", "family": "Family"}
    for r in table.itertuples():
        n = names[r.split]
        lines += [f"\\newcommand{{\\Split{n}Train}}{{{r.n_train:,}}}",
                  f"\\newcommand{{\\Split{n}Test}}{{{r.n_test:,}}}",
                  f"\\newcommand{{\\Split{n}PiTrain}}{{{100 * r.pi_train:.1f}\\%}}",
                  f"\\newcommand{{\\Split{n}PiTest}}{{{100 * r.pi_test:.1f}\\%}}"]
    nums = {
        "CurveSplitMatch": f"{100 * curve_match:.1f}\\%",
        "CurveSplitLookupAcc": f"{100 * curve_acc:.1f}\\%",
        "ClassSplitMatch": f"{100 * class_match:.2f}\\%",
        "ClassSplitLookupAcc": f"{100 * class_acc:.1f}\\%" if class_match else "n/a",
        "SharedApKeys": f"{shared_keys:,}",
    }
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in nums.items()]
    (FIG / "step03_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(table.to_string(index=False))
    for k, v in nums.items():
        print(f"{k:22s} {v}")


if __name__ == "__main__":
    main()
