"""Section 2 numbers and figures: checks on the a_p, and the signal before any training.

    python scripts/figs_step02.py

Reads data/curves.parquet and data/features.parquet; writes notes/figures/step02_*.
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from sklearn.metrics import roc_auc_score

from eclab.data.ecdata import load_curves
from eclab.features import AP_COLUMNS, EXCLUDED, INVARIANTS, PRIMES, load_features
from eclab.tasks import task1_label, task2_label, task2_mask

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "notes" / "figures"
INK, MUTED, GRID = "#1f1f1e", "#6b6a64", "#e4e3dd"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]  # categorical slots 1-3, validated

plt.rcParams.update({
    "font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK, "xtick.color": MUTED,
    "ytick.color": MUTED, "axes.spines.top": False, "axes.spines.right": False,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6, "axes.axisbelow": True,
})


def good_reduction(conductor: np.ndarray) -> np.ndarray:
    """good[i, j]: curve i has good reduction at PRIMES[j]."""
    return np.stack([conductor % p != 0 for p in PRIMES], axis=1)


def main():
    curves = load_curves()
    feats = load_features()
    assert (feats.label.to_numpy() == curves.label.to_numpy()).all()
    rank = curves["rank"].to_numpy()
    ap = feats[AP_COLUMNS].to_numpy().astype(np.float64)
    good = good_reduction(curves.conductor.to_numpy())
    complete = curves.conductor.to_numpy() <= 500_000

    # checks on the full table
    violations = int((feats[AP_COLUMNS].groupby(curves.iso_class.to_numpy()).nunique() > 1).any(axis=1).sum())
    hasse = np.abs(ap) / (2 * np.sqrt(PRIMES))
    semi = feats.semistable.to_numpy()
    w = (-1) ** (feats.n_bad_primes.to_numpy() + 1 + feats.n_nonsplit.to_numpy())
    parity_ok = w[semi] == (-1) ** rank[semi]

    # mean of a_p / sqrt(p) by rank, over curves with good reduction at p (complete range)
    norm = np.where(good, ap / np.sqrt(PRIMES), np.nan)
    fig, ax = plt.subplots(figsize=(6.2, 2.9))
    for k, r in enumerate([0, 1, 2]):
        m = np.nanmean(norm[complete & (rank == r)], axis=0)
        ax.plot(PRIMES, m, color=SERIES[k], lw=2, marker="o", ms=3)
        ax.annotate(f"rank {r}", (PRIMES[-1], m[-1]), xytext=(6, 0), textcoords="offset points",
                    va="center", color=INK, fontsize=8)
    ax.axhline(0, color=MUTED, lw=0.8)
    ax.set_xlim(0, 108)
    ax.set_xlabel("prime p")
    ax.set_ylabel(r"mean of $a_p/\sqrt{p}$")
    fig.tight_layout()
    fig.savefig(FIG / "step02_mean_ap_by_rank.pdf")
    plt.close(fig)

    # a Mestre-Nagao style sum, with no fitting: S = sum over good p < 100 of -a_p log(p) / p
    s = np.nansum(np.where(good, -ap * np.log(PRIMES) / np.array(PRIMES), np.nan), axis=1)
    t2 = complete & task2_mask(rank)
    auc1 = roc_auc_score(task1_label(rank[complete]), s[complete])
    auc2 = roc_auc_score(task2_label(rank[t2]), s[t2])
    mean_s = {r: s[complete & (rank == r)].mean() for r in (0, 1, 2)}

    nums = {
        "NInvariantFeatures": f"{len(INVARIANTS)}",
        "NApFeatures": f"{len(AP_COLUMNS)}",
        "NExcluded": f"{len(EXCLUDED)}",
        "ApClassViolations": f"{violations:,}",
        "NMultiCurveClasses": f"{int((curves.groupby('iso_class').size() > 1).sum()):,}",
        "HasseMax": f"{hasse.max():.3f}",
        "NSemistable": f"{semi.sum():,}",
        "ParityAgree": f"{parity_ok.sum():,}",
        "ParityDisagree": f"{(~parity_ok).sum():,}",
        "SumAucTaskOne": f"{auc1:.3f}",
        "SumAucTaskTwo": f"{auc2:.3f}",
        "MeanSRankZero": f"{mean_s[0]:.2f}",
        "MeanSRankOne": f"{mean_s[1]:.2f}",
        "MeanSRankTwo": f"{mean_s[2]:.2f}",
    }
    lines = ["% generated by scripts/figs_step02.py; do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in nums.items()]
    (FIG / "step02_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for k, v in nums.items():
        print(f"{k:22s} {v}")


if __name__ == "__main__":
    main()
